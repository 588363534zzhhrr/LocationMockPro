package com.antigravity.geospoofer.core

import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import android.content.Intent
import androidx.core.content.FileProvider
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.*
import kotlin.math.PI
import kotlin.math.sin

/**
 * 运动轨迹与标准 GPX 1.1 导出分享引擎
 * 支持将自定义路线或已模拟轨迹导出为高兼容性 GPX 格式，
 * 支持直接唤起系统分享面板（发送至微信、QQ、网盘、Strava、Keep 等）或一键复制 XML 文本。
 */
object GpxExportHelper {

    private val isoDateFormat = SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'", Locale.US).apply {
        timeZone = TimeZone.getTimeZone("UTC")
    }

    /**
     * 生成标准 GPX 1.1 XML 格式字符串
     */
    fun generateGpxString(
        waypoints: List<CoordinateUtils.LatLng>,
        routeName: String = "LocationMockPro_Route",
        speedMps: Float = 3.3f,
        baseElevation: Double = 42.0
    ): String {
        val safeSpeed = if (speedMps > 0.1f) speedMps else 3.3f
        val nowMs = System.currentTimeMillis()
        val xmlBuilder = StringBuilder()

        xmlBuilder.append("""<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="LocationMockPro Stealth Telemetry Engine"
  xmlns="http://www.topografix.com/GPX/1/1"
  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
  xsi:schemaLocation="http://www.topografix.com/GPX/1/1 http://www.topografix.com/GPX/1/1/gpx.xsd">
  <metadata>
    <name><![CDATA[$routeName]]></name>
    <desc>Generated by LocationMockPro Realistic Multi-Sensor Simulator</desc>
    <time>${isoDateFormat.format(Date(nowMs))}</time>
  </metadata>
  <trk>
    <name><![CDATA[$routeName]]></name>
    <type>Running</type>
    <trkseg>
""")

        var cumulativeDist = 0.0
        var currentTimestampMs = nowMs - ((waypoints.size * 1000L)) // 适度回溯时间使之符合运动耗时

        for (i in waypoints.indices) {
            val pt = waypoints[i]
            if (i > 0) {
                val prev = waypoints[i - 1]
                val dist = CoordinateUtils.calculateDistance(prev.latitude, prev.longitude, pt.latitude, pt.longitude)
                cumulativeDist += dist
                val elapsedSec = (dist / safeSpeed).toLong().coerceAtLeast(1L)
                currentTimestampMs += elapsedSec * 1000L
            }

            // 计算平滑地形波浪起伏海拔 (米)
            val elevationWave = sin(cumulativeDist / 350.0 * 2.0 * PI) * 12.0 + sin(cumulativeDist / 70.0 * 2.0 * PI) * 3.0
            val ele = "%.1f".format(Locale.US, (baseElevation + elevationWave).coerceAtLeast(5.0))
            val timeStr = isoDateFormat.format(Date(currentTimestampMs))

            xmlBuilder.append("""      <trkpt lat="${"%.6f".format(Locale.US, pt.latitude)}" lon="${"%.6f".format(Locale.US, pt.longitude)}">
        <ele>$ele</ele>
        <time>$timeStr</time>
      </trkpt>
""")
        }

        xmlBuilder.append("""    </trkseg>
  </trk>
</gpx>""")

        return xmlBuilder.toString()
    }

    /**
     * 将路线导出为缓存文件并调用系统分享
     */
    fun exportAndShareGpx(
        context: Context,
        waypoints: List<CoordinateUtils.LatLng>,
        routeName: String = "轨迹路线",
        speedMps: Float = 3.3f
    ): Boolean {
        if (waypoints.isEmpty()) return false

        try {
            val gpxContent = generateGpxString(waypoints, routeName, speedMps)
            val exportDir = File(context.cacheDir, "exports").apply { mkdirs() }
            val sanitizedName = routeName.replace("[^a-zA-Z0-9\\u4e00-\\u9fa5_-]".toRegex(), "_")
            val fileName = "${sanitizedName}_${System.currentTimeMillis() % 100000}.gpx"
            val file = File(exportDir, fileName)

            FileOutputStream(file).use { out ->
                out.write(gpxContent.toByteArray(Charsets.UTF_8))
            }

            val uri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                file
            )

            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "application/gpx+xml"
                putExtra(Intent.EXTRA_STREAM, uri)
                putExtra(Intent.EXTRA_SUBJECT, "GPX 运动轨迹: $routeName")
                putExtra(Intent.EXTRA_TEXT, "由 LocationMockPro 导出的标准 GPX 运动路线（${waypoints.size} 点位）")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }

            val chooser = Intent.createChooser(shareIntent, "导出与分享 GPX 轨迹文件").apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(chooser)
            return true
        } catch (e: Exception) {
            e.printStackTrace()
            return false
        }
    }

    /**
     * 将 GPX 纯文本复制到剪贴板
     */
    fun copyGpxToClipboard(context: Context, waypoints: List<CoordinateUtils.LatLng>, routeName: String, speedMps: Float): Boolean {
        return try {
            val content = generateGpxString(waypoints, routeName, speedMps)
            val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
            val clip = ClipData.newPlainText("GPX Route XML", content)
            clipboard.setPrimaryClip(clip)
            true
        } catch (e: Exception) {
            e.printStackTrace()
            false
        }
    }
}

package com.antigravity.geospoofer.core

import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import android.content.Intent
import androidx.core.content.FileProvider
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.*
import kotlin.math.PI
import kotlin.math.sin

/**
 * 运动轨迹与标准 GPX 1.1 导出分享引擎
 * 支持将自定义路线或已模拟轨迹导出为高兼容性 GPX 格式（自动纠偏为国际标准 WGS-84 坐标与自然微地形海拔），
 * 支持直接唤起系统分享面板（发送至微信、QQ、网盘、Strava、Keep 等）或一键复制 XML 文本。
 */
object GpxExportHelper {

    private fun createIsoDateFormat(): SimpleDateFormat {
        return SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'", Locale.US).apply {
            timeZone = TimeZone.getTimeZone("UTC")
        }
    }

    /**
     * 生成标准 GPX 1.1 XML 格式字符串
     * @param isGcj02Input 输入路点是否为火星坐标（若是则自动转换为标准 WGS-84 导出）
     */
    fun generateGpxString(
        waypoints: List<CoordinateUtils.LatLng>,
        routeName: String = "LocationMockPro_Route",
        speedMps: Float = 3.3f,
        baseElevation: Double = 35.0,
        isGcj02Input: Boolean = true
    ): String {
        val isoDateFormat = createIsoDateFormat()
        val safeSpeed = if (speedMps > 0.1f) speedMps else 3.3f
        val nowMs = System.currentTimeMillis()
        val xmlBuilder = StringBuilder()

        val wgsWaypoints = if (isGcj02Input) {
            waypoints.map { CoordinateUtils.gcj02ToWgs84(it.latitude, it.longitude) }
        } else {
            waypoints
        }

        val safeName = routeName.replace("]]>", "]]]]><![CDATA[>")

        xmlBuilder.append("""<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="LocationMockPro Stealth Telemetry Engine"
  xmlns="http://www.topografix.com/GPX/1/1"
  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
  xsi:schemaLocation="http://www.topografix.com/GPX/1/1 http://www.topografix.com/GPX/1/1/gpx.xsd">
  <metadata>
    <name><![CDATA[$safeName]]></name>
    <desc>Generated by LocationMockPro Realistic Multi-Sensor Simulator</desc>
    <time>${isoDateFormat.format(Date(nowMs))}</time>
  </metadata>
  <trk>
    <name><![CDATA[$safeName]]></name>
    <type>Running</type>
    <trkseg>
""")

        var cumulativeDist = 0.0
        var totalEstimatedDurationSec = 0L
        for (i in 1 until wgsWaypoints.size) {
            val d = CoordinateUtils.calculateDistance(
                wgsWaypoints[i - 1].latitude, wgsWaypoints[i - 1].longitude,
                wgsWaypoints[i].latitude, wgsWaypoints[i].longitude
            )
            totalEstimatedDurationSec += (d / safeSpeed).toLong().coerceAtLeast(1L)
        }
        var currentTimestampMs = nowMs - (totalEstimatedDurationSec * 1000L)

        for (i in wgsWaypoints.indices) {
            val pt = wgsWaypoints[i]
            if (i > 0) {
                val prev = wgsWaypoints[i - 1]
                val dist = CoordinateUtils.calculateDistance(prev.latitude, prev.longitude, pt.latitude, pt.longitude)
                cumulativeDist += dist
                val elapsedSec = (dist / safeSpeed).toLong().coerceAtLeast(1L)
                currentTimestampMs += elapsedSec * 1000L
            }

            // 与 RouteSimulator 保持一致的三频段自然平缓微地形海拔模型
            val macroSlope = sin(cumulativeDist / 1800.0 * 2.0 * PI) * 2.2
            val mesoSlope = sin(cumulativeDist / 650.0 * 2.0 * PI) * 0.7
            val microTexture = sin(cumulativeDist / 160.0 * 2.0 * PI) * 0.2
            val elevationDelta = macroSlope + mesoSlope + microTexture
            val ele = "%.1f".format(Locale.US, (baseElevation + elevationDelta).coerceAtLeast(4.0))
            val timeStr = isoDateFormat.format(Date(currentTimestampMs))

            xmlBuilder.append("""      <trkpt lat="${"%.6f".format(Locale.US, pt.latitude)}" lon="${"%.6f".format(Locale.US, pt.longitude)}">
        <ele>$ele</ele>
        <time>$timeStr</time>
      </trkpt>
""")
        }

        xmlBuilder.append("""    </trkseg>
  </trk>
</gpx>""")

        return xmlBuilder.toString()
    }

    /**
     * 将路线导出为缓存文件并调用系统分享
     */
    fun exportAndShareGpx(
        context: Context,
        waypoints: List<CoordinateUtils.LatLng>,
        routeName: String = "轨迹路线",
        speedMps: Float = 3.3f,
        isGcj02Input: Boolean = true
    ): Boolean {
        if (waypoints.isEmpty()) return false

        try {
            val gpxContent = generateGpxString(
                waypoints = waypoints,
                routeName = routeName,
                speedMps = speedMps,
                isGcj02Input = isGcj02Input
            )
            val exportDir = File(context.cacheDir, "exports").apply { mkdirs() }
            val sanitizedName = routeName.replace("[^a-zA-Z0-9\\u4e00-\\u9fa5_-]".toRegex(), "_")
            val fileName = "${sanitizedName}_${System.currentTimeMillis() % 100000}.gpx"
            val file = File(exportDir, fileName)

            FileOutputStream(file).use { out ->
                out.write(gpxContent.toByteArray(Charsets.UTF_8))
            }

            val uri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                file
            )

            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "application/gpx+xml"
                putExtra(Intent.EXTRA_STREAM, uri)
                putExtra(Intent.EXTRA_SUBJECT, "GPX 运动轨迹: $routeName")
                putExtra(Intent.EXTRA_TEXT, "由 LocationMockPro 导出的标准 GPX 运动路线（${waypoints.size} 点位）")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }

            val chooser = Intent.createChooser(shareIntent, "导出与分享 GPX 轨迹文件").apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(chooser)
            return true
        } catch (e: Exception) {
            e.printStackTrace()
            return false
        }
    }

    /**
     * 将 GPX 纯文本复制到剪贴板
     */
    fun copyGpxToClipboard(
        context: Context,
        waypoints: List<CoordinateUtils.LatLng>,
        routeName: String,
        speedMps: Float,
        isGcj02Input: Boolean = true
    ): Boolean {
        return try {
            val content = generateGpxString(
                waypoints = waypoints,
                routeName = routeName,
                speedMps = speedMps,
                isGcj02Input = isGcj02Input
            )
            val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
            val clip = ClipData.newPlainText("GPX Route XML", content)
            clipboard.setPrimaryClip(clip)
            true
        } catch (e: Exception) {
            e.printStackTrace()
            false
        }
    }
}
